-- =====================================================
-- 1. LOAI DO UONG
-- =====================================================

CREATE TABLE IF NOT EXISTS HangDienThoai (
    MaLoai BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TenLoai VARCHAR(100) NOT NULL UNIQUE,
    MoTa VARCHAR(255),
    TrangThai BOOLEAN NOT NULL DEFAULT TRUE
);


-- =====================================================
-- 2. NHAN VIEN
-- =====================================================

CREATE TABLE IF NOT EXISTS NhanVien (
    MaNV BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    HoTen VARCHAR(150) NOT NULL,
    GioiTinh VARCHAR(20),
    NgaySinh DATE,
    SDT VARCHAR(20) UNIQUE,
    Email VARCHAR(150),
    DiaChi VARCHAR(255),
    NgayVaoLam DATE DEFAULT CURRENT_DATE,
    TrangThai BOOLEAN NOT NULL DEFAULT TRUE
);


-- =====================================================
-- 3. TAI KHOAN
-- =====================================================

CREATE TABLE IF NOT EXISTS TaiKhoan (
    MaTK BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TenDangNhap VARCHAR(50) NOT NULL UNIQUE,
    MatKhau VARCHAR(255) NOT NULL,
    VaiTro VARCHAR(20) NOT NULL,
    MaNV BIGINT,
    TrangThai BOOLEAN NOT NULL DEFAULT TRUE,
    NgayTao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT CK_TaiKhoan_VaiTro
        CHECK (VaiTro IN ('ADMIN', 'NHANVIEN')),

    CONSTRAINT FK_TaiKhoan_NhanVien
        FOREIGN KEY (MaNV)
        REFERENCES NhanVien(MaNV)
        ON DELETE SET NULL
);

