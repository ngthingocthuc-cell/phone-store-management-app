CREATE TABLE IF NOT EXISTS PhuKien (
    MaPhuKien BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TenPhuKien VARCHAR(100) NOT NULL UNIQUE,
    DonGia DECIMAL(12,2) NOT NULL,
    TrangThai BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT CK_PhuKien_DonGia
        CHECK (DonGia >= 0)
);


-- =====================================================
-- 6. HOA DON
-- =====================================================

CREATE TABLE IF NOT EXISTS HoaDon (
    MaHD BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaNV BIGINT NOT NULL,
    NgayLap TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    TongTien DECIMAL(12,2) NOT NULL DEFAULT 0,
    GiamGia DECIMAL(12,2) NOT NULL DEFAULT 0,
    ThanhTien DECIMAL(12,2) NOT NULL DEFAULT 0,
    PhuongThucTT VARCHAR(50) DEFAULT 'Tiền mặt',
    TrangThai VARCHAR(30) NOT NULL DEFAULT 'Đã thanh toán',
    TenKhachHang VARCHAR(150),
    SDTKhachHang VARCHAR(20),
    GhiChu VARCHAR(255),

    CONSTRAINT FK_HoaDon_NhanVien
        FOREIGN KEY (MaNV)
        REFERENCES NhanVien(MaNV),

    CONSTRAINT CK_HoaDon_Tien
        CHECK (
            TongTien >= 0
            AND GiamGia >= 0
            AND ThanhTien >= 0
        )
);
ALTER TABLE HoaDon ADD COLUMN IF NOT EXISTS SDTKhachHang VARCHAR(20);


-- =====================================================
-- 7. CHI TIET HOA DON
-- Luu ten mon, size va gia tai thoi diem ban
-- =====================================================

CREATE TABLE IF NOT EXISTS HoaDonChiTiet (
    MaCT BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaHD BIGINT NOT NULL,
    MaSP BIGINT NOT NULL,
    TenSanPham VARCHAR(150) NOT NULL,
    DungLuong VARCHAR(30) NOT NULL,
    DonGia DECIMAL(12,2) NOT NULL,
    SoLuong INTEGER NOT NULL,
    ThanhTien DECIMAL(12,2) NOT NULL,

    CONSTRAINT FK_HoaDonChiTiet_HoaDon
        FOREIGN KEY (MaHD)
        REFERENCES HoaDon(MaHD)
        ON DELETE CASCADE,

    CONSTRAINT FK_HoaDonChiTiet_SanPham
        FOREIGN KEY (MaSP)
        REFERENCES SanPham(MaSP),

    CONSTRAINT CK_HoaDonChiTiet_SoLuong
        CHECK (SoLuong > 0)
);

ALTER TABLE HoaDonChiTiet ALTER COLUMN DungLuong VARCHAR(30);

INSERT INTO DungLuong (TenDungLuong)
SELECT DISTINCT ct.DungLuong
FROM HoaDonChiTiet ct
WHERE TRIM(ct.DungLuong) <> ''
  AND NOT EXISTS (
      SELECT 1 FROM DungLuong k
      WHERE UPPER(k.TenDungLuong) = UPPER(ct.DungLuong)
  );


-- =====================================================
-- 8. TOPPING TRONG TUNG DONG HOA DON
-- =====================================================

CREATE TABLE IF NOT EXISTS HoaDonChiTietPhuKien (
    MaCT BIGINT NOT NULL,
    MaPhuKien BIGINT NOT NULL,
    TenPhuKien VARCHAR(100) NOT NULL,
    DonGia DECIMAL(12,2) NOT NULL,
    SoLuong INTEGER NOT NULL DEFAULT 1,
    ThanhTien DECIMAL(12,2) NOT NULL,

    PRIMARY KEY (MaCT, MaPhuKien),

    CONSTRAINT FK_CT_PhuKien_ChiTiet
        FOREIGN KEY (MaCT)
        REFERENCES HoaDonChiTiet(MaCT)
        ON DELETE CASCADE,

    CONSTRAINT FK_CT_PhuKien_PhuKien
        FOREIGN KEY (MaPhuKien)
        REFERENCES PhuKien(MaPhuKien),

    CONSTRAINT CK_CT_PhuKien_SoLuong
        CHECK (SoLuong > 0)
);


