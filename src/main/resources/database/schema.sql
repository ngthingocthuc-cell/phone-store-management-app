CREATE TABLE IF NOT EXISTS RecoveryOtp (
    Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaTK BIGINT NOT NULL REFERENCES TaiKhoan(MaTK) ON DELETE CASCADE,
    CodeHash VARCHAR(64) NOT NULL,
    Salt VARCHAR(36) NOT NULL,
    CreatedAt TIMESTAMP NOT NULL,
    ExpiresAt TIMESTAMP NOT NULL,
    Sent BOOLEAN NOT NULL DEFAULT FALSE,
    Used BOOLEAN NOT NULL DEFAULT FALSE,
    Attempts INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS IDX_RecoveryOtp_Account ON RecoveryOtp(MaTK,Id);

CREATE TABLE IF NOT EXISTS BaoHanh (
    MaBH BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaCT BIGINT NOT NULL REFERENCES HoaDonChiTiet(MaCT),
    IMEI VARCHAR(15) NOT NULL UNIQUE,
    TenKhach VARCHAR(150) NOT NULL,
    SDT VARCHAR(20) NOT NULL,
    NgayBan DATE NOT NULL,
    HetHan DATE NOT NULL,
    TrangThai VARCHAR(30) NOT NULL DEFAULT 'Đang sử dụng',
    GhiChu VARCHAR(500) NOT NULL DEFAULT '',
    CHECK (HetHan >= NgayBan),
    CHECK (TrangThai IN ('Đang sử dụng','Đang sửa','Chờ trả khách','Đã trả khách'))
);
CREATE INDEX IF NOT EXISTS IDX_BaoHanh_Line ON BaoHanh(MaCT);

CREATE TABLE IF NOT EXISTS DienThoaiIMEI (
    MaIMEI BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaSP BIGINT NOT NULL REFERENCES SanPham(MaSP),
    IMEI VARCHAR(15) NOT NULL UNIQUE,
    MaCT BIGINT REFERENCES HoaDonChiTiet(MaCT),
    NgayNhap TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IDX_DienThoaiIMEI_Product ON DienThoaiIMEI(MaSP,MaCT);
