-- =====================================================
-- 4. SAN PHAM / TRA SUA
-- Moi size la mot dong san pham
-- =====================================================

CREATE TABLE IF NOT EXISTS SanPham (
    MaSP BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TenSP VARCHAR(150) NOT NULL,
    MaLoai BIGINT NOT NULL,
    DungLuong VARCHAR(30) NOT NULL,
    DonGia DECIMAL(12,2) NOT NULL,
    MoTa VARCHAR(255),
    TrangThai BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT CK_SanPham_DonGia
        CHECK (DonGia >= 0),

    CONSTRAINT UQ_SanPham_Ten_Size
        UNIQUE (TenSP, DungLuong),

    CONSTRAINT FK_SanPham_Loai
        FOREIGN KEY (MaLoai)
        REFERENCES HangDienThoai(MaLoai)
);

-- Migrate existing installations from the old fixed M/L constraint.
ALTER TABLE SanPham DROP CONSTRAINT IF EXISTS CK_SanPham_DungLuong;
ALTER TABLE SanPham ALTER COLUMN DungLuong VARCHAR(30);

CREATE TABLE IF NOT EXISTS DungLuong (
    MaDungLuong BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TenDungLuong VARCHAR(30) NOT NULL UNIQUE
);

